/* Addresses and magic numbers for miscellaneous ports. */

#ifndef _PORTS_H
#define _PORTS_H

/* Miscellaneous ports (same as i386 — x86-64 uses identical PC hardware). */
#define PCR		0x65
#define PORT_B          0x61
#define TIMER0          0x40
#define TIMER2          0x42
#define TIMER_MODE      0x43

#endif /* _PORTS_H */
